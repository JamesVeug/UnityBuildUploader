using System.IO;
using NUnit.Framework;
using UnityEngine;

namespace Wireframe.UnitTest
{
    /// <summary>
    /// The path the generated Quick Upload menu items file is imported with. AssetDatabase on Unity 2019 to 2021
    /// rejects full paths ("Invalid AssetDatabase path ... Use path relative to the project folder").
    /// </summary>
    [Category("BuildUploader.Core")]
    public class AutoGenerateMenuItemsPathTests
    {
        private const string ExpectedAssetPath = "Assets/ThirdParty/BuildUploader/Editor/AutoGeneratedMenuItems.cs";

        private string m_dataPath;

        [SetUp]
        public void SetUp()
        {
            // Application.dataPath uses forward slashes on every host, while Path.Combine adds the host's separator
            string root = Path.Combine(Path.GetTempPath(), "BuildUploaderMenuItems_" + System.Guid.NewGuid().ToString("N"));
            m_dataPath = Path.Combine(root, "Project", "Assets").Replace('\\', '/');
        }

        [Test]
        public void DefaultFolderIsImportedRelativeToTheProject()
        {
            string filePath = AutoGenerateMenuItems.GetFilePath(m_dataPath, "ThirdParty/BuildUploader");
            Assert.AreEqual(ExpectedAssetPath, AutoGenerateMenuItems.ToAssetDatabasePath(filePath, m_dataPath));
        }

        [Test]
        public void FolderPickedAsAFullPathIsImportedRelativeToTheProject()
        {
            string folder = m_dataPath + "/ThirdParty/BuildUploader";
            string filePath = AutoGenerateMenuItems.GetFilePath(m_dataPath, folder);
            Assert.AreEqual(ExpectedAssetPath, AutoGenerateMenuItems.ToAssetDatabasePath(filePath, m_dataPath));
        }

        [Test]
        public void FolderOutsideTheProjectIsNotImported()
        {
            string outside = Path.Combine(Path.GetTempPath(), "BuildUploaderElsewhere_" + System.Guid.NewGuid().ToString("N"));
            string filePath = AutoGenerateMenuItems.GetFilePath(m_dataPath, outside);
            Assert.IsNull(AutoGenerateMenuItems.ToAssetDatabasePath(filePath, m_dataPath));
        }

        [Test]
        public void ProjectWithASimilarNameIsNotTreatedAsInside()
        {
            string sibling = m_dataPath.Replace("/Project/Assets", "/Project2/Assets/ThirdParty");
            string filePath = AutoGenerateMenuItems.GetFilePath(m_dataPath, sibling);
            Assert.IsNull(AutoGenerateMenuItems.ToAssetDatabasePath(filePath, m_dataPath));
        }

        [Test]
        public void ThisProjectsDataPathGivesAnAssetsPath()
        {
            string filePath = AutoGenerateMenuItems.GetFilePath(Application.dataPath, "ThirdParty/BuildUploader");
            Assert.AreEqual(ExpectedAssetPath, AutoGenerateMenuItems.ToAssetDatabasePath(filePath, Application.dataPath));
        }
    }
}
