using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Wireframe
{
    /// <summary>
    /// Creates a .cs file with Menu Items to assist the user in quickly uploading builds
    /// NOTE: Using this approach because I couldn't find a way to add them dynamically
    /// </summary>
    public static class AutoGenerateMenuItems
    {
        /// <summary>
        /// Listens for when a code change
        /// TODO: I hope this doesn't cause a double compile...
        /// </summary>
        [InitializeOnLoadMethod]
        private static void InitializeOnLoadMethod()
        {
            if (Preferences.AutoGenerateMenuItems)
            {
                GenerateMenuItems(false);
            }
        }

        [MenuItem("Tools/Build Uploader/Quick Upload/Generate Menu Items", false, 2000)]
        private static void GenerateMenuItems()
        {
            GenerateMenuItems(true);
        }
        
        private static void GenerateMenuItems(bool forceSave)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("namespace Wireframe");
            sb.AppendLine("{");
            sb.AppendLine("    /// This file is auto-generated by the Build Uploader package.");
            sb.AppendLine("    /// Do not modify this file directly as changes will be lost when it is regenerated.");
            sb.AppendLine("    /// To stop this from auto generated disable it in Edit->Preferences->Build Uploader->General->Auto generate Quick Upload items.");
            sb.AppendLine("    public static class BuildUploader_AutoGeneratedMenuItems");
            sb.AppendLine("    {");

            List<UploadProfileSavedData> profiles = GetFiles();
            int totalDone = 0;
            
            HashSet<string> usedGUIDS = new HashSet<string>();
            for (var i = 0; i < profiles.Count; i++)
            {
                if (!usedGUIDS.Add(profiles[i].GUID))
                {
                    continue;
                }

                totalDone++;
                if (totalDone > 1)
                {
                    sb.AppendLine("");
                }
                
                var data = profiles[i];
                string menuitemName = $"Tools/Build Uploader/Quick Upload/{totalDone}. {data.ProfileName}";
                sb.AppendLine($"        [UnityEditor.MenuItem(\"{menuitemName}\")]");
                sb.AppendLine($"        public static void BuildUploader_QuickUpload_{data.GUID}()");
                sb.AppendLine($"        {{");
                sb.AppendLine($"            AutoGenerateMenuItems.BeginUploadingProfile(\"{data.GUID}\", \"{data.ProfileName}\");");
                sb.AppendLine($"        }}");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            string folder = BuildUploaderProjectSettings.Instance.AutoGenerateMenuItemPath;
            string filePath = GetFilePath(Application.dataPath, folder);
            if (Utils.PathContainsInvalidCharacters(filePath))
            {
                Debug.LogError("Unable to generate Menu Items for Build Uploader because the path is invalid.");
                return;
            }
            
            if (!Directory.Exists(Path.GetDirectoryName(filePath)))
            {
                Directory.CreateDirectory(Path.GetDirectoryName(filePath));
            }
            
            string newContent = sb.ToString();
            
            // Only write if content changed
            if (forceSave || !File.Exists(filePath) || File.ReadAllText(filePath) != newContent)
            {
                File.WriteAllText(filePath, newContent);

                string assetPath = ToAssetDatabasePath(filePath, Application.dataPath);
                if (assetPath != null)
                {
                    AssetDatabase.ImportAsset(assetPath);
                }
                else
                {
                    Debug.LogWarning($"Build Uploader wrote its Quick Upload menu items to {filePath}, which is outside the project, so Unity will not compile them. Change Auto Generated Files Path in Project Settings > Build Uploader to a folder under Assets.");
                }
            }
        }

        /// <summary>
        /// Where the generated menu items file goes. The folder is relative to Assets, or a full path when it was
        /// picked with the folder button.
        /// </summary>
        internal static string GetFilePath(string dataPath, string folder)
        {
            return Path.Combine(dataPath, folder, "Editor", "AutoGeneratedMenuItems.cs");
        }

        /// <summary>
        /// The project-relative, forward-slash path AssetDatabase needs (e.g. Assets/ThirdParty/BuildUploader/...).
        /// Unity 2019 to 2021 reject full paths. Returns null when the file is outside the project.
        /// </summary>
        internal static string ToAssetDatabasePath(string filePath, string dataPath)
        {
            string projectRoot = Path.GetDirectoryName(Path.GetFullPath(dataPath));
            if (string.IsNullOrEmpty(projectRoot))
            {
                return null;
            }

            string root = projectRoot.Replace('\\', '/').TrimEnd('/') + "/";
            string fullPath = Path.GetFullPath(filePath).Replace('\\', '/');
            if (!fullPath.StartsWith(root, StringComparison.OrdinalIgnoreCase))
            {
                return null;
            }

            return fullPath.Substring(root.Length);
        }

        /// <summary>
        /// Called by auto-generated code
        /// </summary>
        /// <param name="guid"></param>
        /// <param name="profileName"></param>
        public static void BeginUploadingProfile(string guid, string profileName)
        {
            UploadProfileMeta metaData = new UploadProfileMeta();
            metaData.GUID = guid;
            metaData.ProfileName = profileName;
            QuickUploadPopup.ShowWindow(metaData);
        }

        private static List<UploadProfileSavedData> GetFiles()
        {
            List<UploadProfileSavedData> profiles = new List<UploadProfileSavedData>();
            string path = WindowUploadTab.UploadProfilePath;
            if (string.IsNullOrEmpty(path) || !Directory.Exists(path))
            {
                return profiles;
            }
            
            string[] files = Directory.GetFiles(path, "*.json");
            if (files.Length > 0)
            {
                for (int j = 0; j < files.Length; j++)
                {
                    string file = files[j];
                    string json = File.ReadAllText(file);
                    UploadProfileSavedData savedData;
                    try
                    {
                        savedData = UploadProfileSavedData.FromJSON(json);
                    }
                    catch (Exception)
                    {
                        continue;
                    }

                    if (savedData == null || string.IsNullOrEmpty(savedData.GUID))
                    {
                        continue;
                    }

                    profiles.Add(savedData);
                }

                if (profiles.Count > 0)
                {
                    profiles.Sort((a, b) =>
                    {
                        int compare = String.Compare(a.ProfileName, b.ProfileName, StringComparison.Ordinal);
                        if (compare == 0)
                        {
                            return String.Compare(a.GUID, b.GUID, StringComparison.Ordinal);
                        }

                        return compare;
                    });
                }
            }

            return profiles;
        }
    }
}